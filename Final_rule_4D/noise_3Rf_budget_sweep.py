"""Fixed uniform-3Rf noise sweep over five representative budgets.

The acquisition path is generated by the same 4D LQEI implementation and
selected RKHS objective as the noise-sensitivity experiment.  The three final
rules only postprocess the shared terminal posterior from each path.
"""

from __future__ import annotations

import argparse
import csv
import json
import os
from concurrent.futures import ProcessPoolExecutor, as_completed
from pathlib import Path

for _name in (
    "OMP_NUM_THREADS",
    "OPENBLAS_NUM_THREADS",
    "MKL_NUM_THREADS",
    "NUMEXPR_NUM_THREADS",
):
    os.environ.setdefault(_name, "1")

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from scipy.stats import t

import analyze as plot_style
import experiment as study


HERE = Path(__file__).resolve().parent
OUTPUT = HERE / "noise_3Rf_budget_sweep"
CHECKPOINTS = OUTPUT / "checkpoints"
FIGURES = OUTPUT / "figures"

BUDGET_GRID = (
    (8.0, 2981),
    (8.5, 4915),
    (9.0, 8103),
    (9.5, 13360),
    (10.0, 22026),
)
NOISE_LABEL = "noise_3p0"
NOISE_MULTIPLIER = 3.0
MACROS = 100
CANDIDATES = 2048
PHASE = 92530
PLOT_RULES = (
    study.RULE_PLUS,
    study.RULE_MEAN,
    study.RULE_MINUS_SYMMETRIC,
)


def _checkpoint(budget: int, macro: int) -> Path:
    return CHECKPOINTS / f"T_{budget}" / f"macro_{macro:03d}.json"


def _worker(
    payload: tuple[dict[str, object], int, int],
) -> list[dict[str, object]]:
    function_data, budget, macro = payload
    return study.run_macro(
        study.objective_from_dict(function_data),
        NOISE_LABEL,
        budget,
        CANDIDATES,
        macro,
        PHASE,
        continuous=True,
        noise_multiplier=NOISE_MULTIPLIER,
        final_rules=PLOT_RULES,
    )


def _checkpoint_is_current(budget: int, macro: int) -> bool:
    path = _checkpoint(budget, macro)
    if not path.exists():
        return False
    try:
        rows = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return False
    return (
        len(rows) == len(PLOT_RULES)
        and {str(row.get("rule")) for row in rows} == set(PLOT_RULES)
        and {int(row.get("total_budget", -1)) for row in rows} == {budget}
        and {
            float(row.get("noise_sd_multiplier", float("nan"))) for row in rows
        }
        == {NOISE_MULTIPLIER}
    )


def run(workers: int) -> None:
    function_source = HERE / "formal_all_budgets" / "selected_function.json"
    function_data = json.loads(function_source.read_text(encoding="utf-8"))
    jobs = [
        (function_data, budget, macro)
        for _, budget in BUDGET_GRID
        for macro in range(1, MACROS + 1)
        if not _checkpoint_is_current(budget, macro)
    ]
    print(f"uniform-3Rf budget-sweep paths remaining: {len(jobs)}", flush=True)
    if not jobs:
        return

    with ProcessPoolExecutor(max_workers=workers) as executor:
        futures = {
            executor.submit(_worker, payload): (payload[1], payload[2])
            for payload in jobs
        }
        completed = 0
        for future in as_completed(futures):
            budget, macro = futures[future]
            rows = future.result()
            destination = _checkpoint(budget, macro)
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(
                json.dumps(rows, indent=2) + "\n", encoding="utf-8"
            )
            completed += 1
            if completed % 20 == 0 or completed == len(jobs):
                print(f"completed {completed}/{len(jobs)}", flush=True)


def load_rows() -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    for _, budget in BUDGET_GRID:
        for macro in range(1, MACROS + 1):
            path = _checkpoint(budget, macro)
            if not path.exists():
                raise FileNotFoundError(f"Missing checkpoint: {path}")
            rows.extend(json.loads(path.read_text(encoding="utf-8")))
    budget_order = {budget: index for index, (_, budget) in enumerate(BUDGET_GRID)}
    rule_order = {rule: index for index, rule in enumerate(PLOT_RULES)}
    return sorted(
        rows,
        key=lambda row: (
            budget_order[int(row["total_budget"])],
            int(row["macro"]),
            rule_order[str(row["rule"])],
        ),
    )


def write_csv(path: Path, rows: list[dict[str, object]]) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def summarize(rows: list[dict[str, object]]) -> list[dict[str, object]]:
    summaries: list[dict[str, object]] = []
    for exponent, budget in BUDGET_GRID:
        for rule in PLOT_RULES:
            values = np.asarray(
                [
                    float(row["raw_gap"])
                    for row in rows
                    if int(row["total_budget"]) == budget
                    and str(row["rule"]) == rule
                ],
                dtype=float,
            )
            half_width = float(
                t.ppf(0.975, values.size - 1)
                * np.std(values, ddof=1)
                / np.sqrt(values.size)
            )
            summaries.append(
                {
                    "budget_exponent": exponent,
                    "total_budget": budget,
                    "noise_sd_multiplier": NOISE_MULTIPLIER,
                    "rule": rule,
                    "count": values.size,
                    "mean_raw_gap": float(np.mean(values)),
                    "std_raw_gap": float(np.std(values, ddof=1)),
                    "median_raw_gap": float(np.median(values)),
                    "q25_raw_gap": float(np.quantile(values, 0.25)),
                    "q75_raw_gap": float(np.quantile(values, 0.75)),
                    "ci95_lower": float(np.mean(values) - half_width),
                    "ci95_upper": float(np.mean(values) + half_width),
                }
            )
    return summaries


def paired_comparisons(rows: list[dict[str, object]]) -> list[dict[str, object]]:
    comparisons: list[dict[str, object]] = []
    for exponent, budget in BUDGET_GRID:
        baseline = {
            int(row["macro"]): float(row["raw_gap"])
            for row in rows
            if int(row["total_budget"]) == budget
            and str(row["rule"]) == study.RULE_PLUS
        }
        for comparison in (study.RULE_MEAN, study.RULE_MINUS_SYMMETRIC):
            other = {
                int(row["macro"]): float(row["raw_gap"])
                for row in rows
                if int(row["total_budget"]) == budget
                and str(row["rule"]) == comparison
            }
            macros = sorted(set(baseline) & set(other))
            differences = np.asarray(
                [other[macro] - baseline[macro] for macro in macros], dtype=float
            )
            half_width = float(
                t.ppf(0.975, differences.size - 1)
                * np.std(differences, ddof=1)
                / np.sqrt(differences.size)
            )
            comparisons.append(
                {
                    "budget_exponent": exponent,
                    "total_budget": budget,
                    "noise_sd_multiplier": NOISE_MULTIPLIER,
                    "comparison_rule": comparison,
                    "paired_count": differences.size,
                    "mean_difference_comparison_minus_plus_0p2": float(
                        np.mean(differences)
                    ),
                    "ci95_lower": float(np.mean(differences) - half_width),
                    "ci95_upper": float(np.mean(differences) + half_width),
                    "plus_0p2_win_rate": float(np.mean(differences > 0.0)),
                    "tie_rate": float(np.mean(differences == 0.0)),
                }
            )
    return comparisons


def _budget_tick_labels() -> list[str]:
    return [
        f"$e^{{{exponent:g}}}$\n({budget})" for exponent, budget in BUDGET_GRID
    ]


def plot_boxplots(rows: list[dict[str, object]]) -> None:
    positions = np.arange(len(BUDGET_GRID), dtype=float)
    offsets = (-0.24, 0.0, 0.24)
    figure, axis = plt.subplots(figsize=(14.2, 6.4))
    for offset, rule in zip(offsets, PLOT_RULES, strict=True):
        groups = [
            np.asarray(
                [
                    float(row["raw_gap"])
                    for row in rows
                    if int(row["total_budget"]) == budget
                    and str(row["rule"]) == rule
                ]
            )
            for _, budget in BUDGET_GRID
        ]
        boxes = axis.boxplot(
            groups,
            positions=positions + offset,
            widths=0.21,
            patch_artist=True,
            showfliers=False,
            manage_ticks=False,
            medianprops={"color": "#202020", "linewidth": 1.4},
            whiskerprops={"linewidth": 1.1},
            capprops={"linewidth": 1.1},
        )
        for patch in boxes["boxes"]:
            patch.set_facecolor(plot_style.COLORS[rule])
            patch.set_alpha(0.78)
        axis.plot(
            [],
            [],
            color=plot_style.COLORS[rule],
            linewidth=9,
            alpha=0.78,
            label=plot_style.DISPLAY[rule],
        )

    axis.set_xticks(positions, _budget_tick_labels())
    axis.set_xlabel("Total simulation budget")
    axis.set_ylabel("raw GAP")
    axis.set_title(
        r"4D final-rule ablation under uniform noise "
        r"($\sigma_\epsilon=3R_f$)"
    )
    axis.set_ylim(bottom=-0.035)
    axis.grid(axis="y", alpha=0.22)
    axis.legend(loc="upper center", ncol=3, frameon=True)
    figure.subplots_adjust(left=0.075, right=0.985, bottom=0.15, top=0.91)
    figure.savefig(FIGURES / "final_rule_boxplots_uniform_3Rf.png", dpi=240)
    figure.savefig(FIGURES / "final_rule_boxplots_uniform_3Rf.pdf")
    plt.close(figure)


def plot_average_gap(summaries: list[dict[str, object]]) -> None:
    exponents = np.asarray([exponent for exponent, _ in BUDGET_GRID])
    figure, axis = plt.subplots(figsize=(10.8, 6.2))
    markers = ("o", "s", "^")
    for marker, rule in zip(markers, PLOT_RULES, strict=True):
        subset = [row for row in summaries if str(row["rule"]) == rule]
        means = np.asarray([float(row["mean_raw_gap"]) for row in subset])
        lower = np.asarray([float(row["ci95_lower"]) for row in subset])
        upper = np.asarray([float(row["ci95_upper"]) for row in subset])
        color = plot_style.COLORS[rule]
        axis.plot(
            exponents,
            means,
            color=color,
            marker=marker,
            markersize=7,
            linewidth=2.4,
            label=plot_style.DISPLAY[rule],
        )
        axis.fill_between(exponents, lower, upper, color=color, alpha=0.14)

    axis.set_xticks(exponents, [rf"$e^{{{value:g}}}$" for value in exponents])
    axis.set_xlabel("Total simulation budget")
    axis.set_ylabel("Average raw GAP")
    axis.set_title(
        r"Average final-rule performance under uniform noise "
        r"($\sigma_\epsilon=3R_f$)"
    )
    axis.set_ylim(bottom=-0.02)
    axis.grid(alpha=0.22)
    axis.legend(loc="best", frameon=True)
    figure.subplots_adjust(left=0.10, right=0.98, bottom=0.13, top=0.90)
    figure.savefig(FIGURES / "average_raw_gap_trend_uniform_3Rf.png", dpi=240)
    figure.savefig(FIGURES / "average_raw_gap_trend_uniform_3Rf.pdf")
    plt.close(figure)


def write_report(
    summaries: list[dict[str, object]], comparisons: list[dict[str, object]]
) -> None:
    lines = [
        "# Uniform 3Rf budget sweep",
        "",
        (
            "The 4D RKHS objective, GP, initial-design construction, sequential "
            "LQEI acquisition, and candidate-pool size are unchanged from the "
            "final noise-sensitivity experiment. The pointwise observation-noise "
            "standard deviation is fixed uniformly at 3 R_f. Each budget contains "
            f"{MACROS} complete LQEI paths."
        ),
        "",
        "## Average raw GAP",
        "",
        "| Budget | +0.2 Lambda | posterior mean | -0.2 Lambda |",
        "|---:|---:|---:|---:|",
    ]
    for exponent, budget in BUDGET_GRID:
        values = {
            str(row["rule"]): float(row["mean_raw_gap"])
            for row in summaries
            if int(row["total_budget"]) == budget
        }
        lines.append(
            f"| e^{exponent:g} = {budget} | {values[study.RULE_PLUS]:.6f} | "
            f"{values[study.RULE_MEAN]:.6f} | "
            f"{values[study.RULE_MINUS_SYMMETRIC]:.6f} |"
        )
    lines.extend(
        [
            "",
            "## Validation",
            "",
            f"- Complete sequential LQEI paths: {len(BUDGET_GRID) * MACROS}.",
            f"- Terminal recommendations: {len(BUDGET_GRID) * MACROS * len(PLOT_RULES)}.",
            "- All points use the same noise standard deviation within a path.",
            "- All three final rules share the sampled points and terminal posterior within a path.",
            "- Boxplot outlier markers are hidden; no observations are removed from analysis.",
            "- Trend ribbons are 95% confidence intervals for the average raw GAP.",
            "",
            "## Paired comparison against +0.2 Lambda",
            "",
            "| Budget | comparison | mean GAP difference | 95% CI | +0.2 win rate |",
            "|---:|---|---:|---:|---:|",
        ]
    )
    for row in comparisons:
        lines.append(
            f"| e^{float(row['budget_exponent']):g} | "
            f"{plot_style.DISPLAY[str(row['comparison_rule'])]} | "
            f"{float(row['mean_difference_comparison_minus_plus_0p2']):.6f} | "
            f"[{float(row['ci95_lower']):.6f}, {float(row['ci95_upper']):.6f}] | "
            f"{float(row['plus_0p2_win_rate']):.1%} |"
        )
    (OUTPUT / "REPORT.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def analyze() -> None:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    FIGURES.mkdir(parents=True, exist_ok=True)
    rows = load_rows()
    summaries = summarize(rows)
    comparisons = paired_comparisons(rows)
    write_csv(OUTPUT / "all_recommendations.csv", rows)
    write_csv(OUTPUT / "summary.csv", summaries)
    write_csv(OUTPUT / "paired_comparisons.csv", comparisons)
    plot_boxplots(rows)
    plot_average_gap(summaries)
    write_report(summaries, comparisons)

    counts = {
        (budget, rule): sum(
            int(row["total_budget"]) == budget and str(row["rule"]) == rule
            for row in rows
        )
        for _, budget in BUDGET_GRID
        for rule in PLOT_RULES
    }
    validation = {
        "scenario": rows[0]["scenario"],
        "budget_grid": [
            {"exponent": exponent, "budget": budget}
            for exponent, budget in BUDGET_GRID
        ],
        "noise_sd_multiplier": NOISE_MULTIPLIER,
        "paths": len(rows) // len(PLOT_RULES),
        "recommendations": len(rows),
        "all_budget_rule_counts_equal_100": set(counts.values()) == {MACROS},
        "uniform_noise": True,
        "same_terminal_posterior_within_path": True,
        "full_sequential_acquisition": True,
        "continuous_acquisition_polish": True,
        "candidate_count": CANDIDATES,
        "plotted_rules": list(PLOT_RULES),
    }
    (OUTPUT / "validation_report.json").write_text(
        json.dumps(validation, indent=2) + "\n", encoding="utf-8"
    )
    source = HERE / "formal_all_budgets" / "selected_function.json"
    (OUTPUT / "selected_function.json").write_text(
        source.read_text(encoding="utf-8"), encoding="utf-8"
    )
    print(json.dumps(validation, indent=2), flush=True)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "mode", choices=("run", "analyze", "all"), nargs="?", default="all"
    )
    parser.add_argument(
        "--workers", type=int, default=max(1, min(8, os.cpu_count() or 1))
    )
    args = parser.parse_args()
    if args.mode in ("run", "all"):
        run(args.workers)
    if args.mode in ("analyze", "all"):
        analyze()


if __name__ == "__main__":
    main()
